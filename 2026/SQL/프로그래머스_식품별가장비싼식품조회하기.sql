SELECT FP.CATEGORY, PRICE MAX_PRICE, PRODUCT_NAME
FROM FOOD_PRODUCT FP JOIN 
(SELECT CATEGORY, MAX(PRICE) AS MAX_PRICE
FROM FOOD_PRODUCT
GROUP BY CATEGORY
)MP ON FP.CATEGORY=MP.CATEGORY
WHERE FP.PRICE=MP.MAX_PRICE AND FP.CATEGORY IN ('과자','국','김치','식용유')
ORDER BY PRICE DESC;