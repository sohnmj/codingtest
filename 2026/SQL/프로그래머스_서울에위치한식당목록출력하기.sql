/*
[로직] REST_INFO+REST_REVIEW 조인 후 서울 식당별 리뷰 평균
[문법] LIKE '서울%'로 '서울'로 시작하는 주소 찾기, ROUND(AVG(x),2)는 셋째 자리에서 반올림해 둘째 자리까지
[엣지] GROUP BY REST_ID만 해도 REST_ID가 PK라 나머지 컬럼을 그냥 SELECT 가능, 정렬은 SCORE DESC 다음 FAVORITES DESC로 둘 다 DESC 명시
*/
SELECT REST_ID, REST_NAME, FOOD_TYPE, FAVORITES, ADDRESS,ROUND(AVG(REVIEW_SCORE),2) AS SCORE
FROM REST_INFO JOIN REST_REVIEW USING(REST_ID)
WHERE ADDRESS LIKE '서울%'
GROUP BY REST_ID
ORDER BY SCORE DESC, FAVORITES DESC;
