/*
[로직] BOOK(가격)·AUTHOR·BOOK_SALES(판매량)를 조인해 저자+카테고리별로 2022년 1월 매출(PRICE*SALES)을 합산
[문법] JOIN USING(같은 이름 컬럼), SELECT의 비집계 컬럼은 GROUP BY에 괄호 없이 나열, 집계는 SUM(PRICE*SALES)
[실수] 문제를 잘 읽자: SUM(BOOK_ID)*SALES로 식별자를 더함 → 매출은 PRICE*SALES, 곱셈은 SUM 안에. GROUP BY (a,b,c) 괄호도 금지
[엣지] ORDER BY의 DESC는 바로 앞 컬럼에만 적용 → AUTHOR_ID ASC, CATEGORY DESC로 명시. 1월 판매가 없는 저자는 조인에서 자연히 제외
*/
SELECT AUTHOR_ID, AUTHOR_NAME, CATEGORY, SUM(PRICE * SALES) AS TOTAL_SALES
FROM BOOK
JOIN AUTHOR USING (AUTHOR_ID)
JOIN BOOK_SALES USING (BOOK_ID)
WHERE YEAR(SALES_DATE) = 2022 AND MONTH(SALES_DATE) = 1
GROUP BY AUTHOR_ID, AUTHOR_NAME, CATEGORY
ORDER BY AUTHOR_ID ASC, CATEGORY DESC;