/*
[로직] CAR+HISTORY 조인, DISCOUNT_PLAN은 LEFT JOIN 후 기록별 MIN(금액)=최대 할인
[문법] SUBSTRING_INDEX(DURATION_TYPE,'일',1)+CAST AS UNSIGNED로 숫자 추출. 오른쪽 테이블 조건은 WHERE 말고 ON에
[실수] DATEDIFF에 +1 빠뜨림(시작일 포함). INNER JOIN+WHERE로 7일 미만 기록이 통째로 사라짐. FEE를 FLOOR로 정수화 안 함
[엣지] 7일 미만은 할인 NULL → IFNULL(DISCOUNT_RATE,0). 딱 7·30·90일도 +1 해야 할인 구간에 포함
*/
SELECT H.HISTORY_ID,
       FLOOR(MIN(C.DAILY_FEE * (DATEDIFF(H.END_DATE, H.START_DATE) + 1)
                 * (100 - IFNULL(P.DISCOUNT_RATE, 0)) / 100)) AS FEE
FROM CAR_RENTAL_COMPANY_CAR C
JOIN CAR_RENTAL_COMPANY_RENTAL_HISTORY H
  ON C.CAR_ID = H.CAR_ID
LEFT JOIN CAR_RENTAL_COMPANY_DISCOUNT_PLAN P
  ON P.CAR_TYPE = C.CAR_TYPE
 AND DATEDIFF(H.END_DATE, H.START_DATE) + 1
     >= CAST(SUBSTRING_INDEX(P.DURATION_TYPE, '일', 1) AS UNSIGNED)
WHERE C.CAR_TYPE = '트럭'
GROUP BY H.HISTORY_ID
ORDER BY FEE DESC, H.HISTORY_ID DESC;