/*
[로직] PATIENT+APPOINTMENT+DOCTOR 조인 후 4/13 CS과 미취소 예약 조회
[문법] JOIN USING(PT_NO)과 JOIN ON 섞어 쓰기, 두 테이블에 같은 이름 컬럼(MCDP_CD)이 있으면 APPOINTMENT.MCDP_CD처럼 테이블명 붙이기
[엣지] APNT_YMD는 DATETIME이라 ='2022-04-13'로 바로 비교하면 0건 → DATE(APNT_YMD)로 날짜만 잘라 비교, 취소는 APNT_CNCL_YN='N'
*/
SELECT APNT_NO, PT_NAME, PT_NO, APPOINTMENT.MCDP_CD,DR_NAME, APNT_YMD
FROM PATIENT JOIN APPOINTMENT USING(PT_NO)
JOIN DOCTOR ON MDDR_ID=DR_ID
WHERE DATE(APNT_YMD)='2022-04-13' AND APNT_CNCL_YN='N' AND APPOINTMENT.MCDP_CD='CS'
ORDER BY APNT_YMD
