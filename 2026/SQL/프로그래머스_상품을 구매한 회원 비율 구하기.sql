/*
[로직] USER_INFO+ONLINE_SALE 조인 후 2021년 가입자의 년·월별 구매 회원 수와 비율
[문법] 절 순서 WHERE→GROUP BY→HAVING→ORDER BY, NULL 비교는 IS (NOT) NULL만 가능, 전체 분모는 서브쿼리로
[실수] COUNT(ONLINE_SALE_ID)=판매 건수 → 회원 수는 COUNT(DISTINCT USER_ID), 분모 COUNT(*)는 그룹 행 수일 뿐
[엣지] 한 회원의 같은 달 중복 구매 → DISTINCT로 제거, 비율은 ROUND(...,1)로 소수 둘째 자리에서 반올림
*/
SELECT YEAR(O.SALES_DATE) AS YEAR,
       MONTH(O.SALES_DATE) AS MONTH,
       COUNT(DISTINCT O.USER_ID) AS PURCHASED_USERS,
       ROUND(COUNT(DISTINCT O.USER_ID) /
             (SELECT COUNT(*) FROM USER_INFO WHERE YEAR(JOINED) = 2021), 1) AS PURCHASED_RATIO
FROM USER_INFO U
JOIN ONLINE_SALE O ON U.USER_ID = O.USER_ID
WHERE YEAR(U.JOINED) = 2021
GROUP BY YEAR, MONTH
ORDER BY YEAR, MONTH;