/*
[로직] USER_INFO+ONLINE_SALE 조인 후 년·월·성별별 구매 회원 수
[문법] JOIN USING(USER_ID), GROUP BY는 괄호 없이 나열, SELECT 별칭(YEAR, MONTH)을 GROUP BY·ORDER BY에 재사용
[실수] GROUP BY (a,b,c) 괄호 → 에러. COUNT(USER_ID)가 GENDER NULL까지 걸러줄 거라 착각 → WHERE GENDER IS NOT NULL
[엣지] 한 회원이 같은 년·월에 여러 번 구매 가능 → 판매 행이 중복 → COUNT(DISTINCT USER_ID)로 회원 수 세기
*/
SELECT YEAR(SALES_DATE) AS YEAR,
       MONTH(SALES_DATE) AS MONTH,
       GENDER,
       COUNT(DISTINCT USER_ID) AS USERS
FROM USER_INFO
JOIN ONLINE_SALE USING (USER_ID)
WHERE GENDER IS NOT NULL
GROUP BY YEAR, MONTH, GENDER
ORDER BY YEAR, MONTH, GENDER;