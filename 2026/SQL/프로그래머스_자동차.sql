/*
[로직] CAR+HISTORY(LEFT)+DISCOUNT_PLAN 조인 후 차별로 묶어 11월 겹침 0건인 차만
[문법] SUM(조건식)으로 개수 세기(참=1), COALESCE(NULL,0), HAVING에서 SELECT 별칭 FEE 사용
[실수] WHERE는 기록 한 줄씩 검사 → 다른 기록이 겹쳐도 통과됨. 차 단위 판단은 GROUP BY+HAVING
[엣지] 겹침=START<=11-30 AND END>=11-01, 기록 없는 차는 LEFT JOIN+COALESCE, FEE는 FLOOR+범위조건
*/
SELECT C.CAR_ID, C.CAR_TYPE,
       FLOOR(C.DAILY_FEE * 30 * (100 - P.DISCOUNT_RATE) / 100) AS FEE
FROM CAR_RENTAL_COMPANY_CAR C
LEFT JOIN CAR_RENTAL_COMPANY_RENTAL_HISTORY H USING (CAR_ID)
JOIN CAR_RENTAL_COMPANY_DISCOUNT_PLAN P
  ON C.CAR_TYPE = P.CAR_TYPE AND P.DURATION_TYPE = '30일 이상'
WHERE C.CAR_TYPE IN ('세단', 'SUV')
GROUP BY C.CAR_ID, C.CAR_TYPE, C.DAILY_FEE, P.DISCOUNT_RATE
HAVING COALESCE(SUM(H.START_DATE <= '2022-11-30' AND H.END_DATE >= '2022-11-01'), 0) = 0
   AND FEE >= 500000 AND FEE < 2000000
ORDER BY FEE DESC, C.CAR_TYPE, C.CAR_ID DESC;